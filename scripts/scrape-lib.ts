/**
 * The scraper's logic, with all I/O (cache, network, files, delays, logging) injected so it can be tested.
 * scripts/scrape-bricklink.ts wires it to the real file system and network.
 */
import { must, type SetInventory, type VersionDef } from '../src/data/types';
import { defaultDefs, effectiveChanges, mergeChanges } from '../src/logic/versions';
import { parseChangelog, parseInventory, type ChangeGroup } from './parse';

export const INVENTORY_URL = (setNo: string) => `https://www.bricklink.com/catalogItemInv.asp?S=${setNo}`;
export const CATALOG_URL = (setNo: string) => `https://www.bricklink.com/v2/catalog/catalogitem.page?S=${setNo}`;
export const CHANGELOG_URL = (setNo: string) =>
  `https://www.bricklink.com/catalogInvChangeItem.asp?itemType=S&itemNo=${setNo}&viewDate=Y&viewStatus=1`;

/** Versions closer together than this (days) are probably the same production run. */
export const SAME_RUN_DAYS = 183;
const DAY_MS = 86400000;

export interface Io {
  /** Cached page by file name, or undefined when not cached. */
  readCache(name: string): string | undefined;
  writeCache(name: string, html: string): void;
  /** A local file given as "setNo=path.html" in sets.txt. */
  readFile(path: string): string;
  fetchHtml(url: string): Promise<{ ok: boolean; status: number; html: string }>;
  sleep(ms: number): Promise<void>;
}

export interface VersionData {
  overrides: Record<string, VersionDef[]>;
  extra: Record<string, VersionDef[]>;
  merge: Record<string, string[][]>;
}

export type Entry =
  | { type: 'listed'; setNo: string; name: string }
  | { type: 'local'; setNo: string; path: string }
  | { type: 'url'; setNo: string; url: string };

/** Parse sets.txt: blank lines and "#" comments are ignored; "!setNo name" = listed only; "setNo=file" = local file; else a BrickLink URL. */
export function parseSetsFile(text: string): Entry[] {
  return text
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'))
    .map((line): Entry => {
      if (line.startsWith('!')) {
        const [setNo, ...rest] = line.slice(1).split(/\s+/);
        return { type: 'listed', setNo, name: rest.join(' ') };
      }
      if (line.includes('=') && !line.startsWith('http')) {
        const [setNo, path] = line.split('=');
        return { type: 'local', setNo, path };
      }
      return { type: 'url', setNo: must(new URL(line).searchParams.get('S'), `S parameter in ${line}`), url: line };
    });
}

/** BrickLink dates ("Jul 2, 2023") as UTC milliseconds, so day counts do not depend on the machine's time zone. */
const utc = (date: string) => Date.parse(`${date} UTC`);

/** Warn about consecutive versions that are suspiciously close together. */
export function sameRunWarnings(setNo: string, changes: ChangeGroup[]): string[] {
  const out: string[] = [];
  for (let k = 1; k < changes.length; k++) {
    const latest = changes[k].date.replace(/^.* \+ /, ''); // a merged group is "first + ... + last"
    const earliestBefore = changes[k - 1].date.replace(/ \+ .*$/, '');
    const gap = (utc(latest) - utc(earliestBefore)) / DAY_MS;
    if (gap <= SAME_RUN_DAYS)
      out.push(
        `  WARN ${setNo}: "${changes[k - 1].date}" and "${changes[k].date}" are ${Math.round(gap)} days apart - same production run? Merge via mergeDates in src/data/versions.ts`,
      );
  }
  return out;
}

/** Contents of the generated data module. */
export const renderGenerated = (sets: SetInventory[]) =>
  `// GENERATED by scripts/scrape-bricklink.ts - do not edit\nimport type { SetInventory } from './types';\nexport const sets: SetInventory[] = ${JSON.stringify(sets, null, 1)};\n`;

export interface ScrapeOptions {
  entries: Entry[];
  refresh: boolean;
  io: Io;
  data: VersionData;
  log: (msg: string) => void;
  warn: (msg: string) => void;
}

const PAGE_DELAY_MS = 1500;

async function loadInventoryHtml(entry: Entry & { type: 'url' }, o: ScrapeOptions): Promise<string> {
  const name = `${entry.setNo}.html`;
  const cached = o.refresh ? undefined : o.io.readCache(name);
  if (cached !== undefined) return cached;
  o.log(`fetching ${entry.setNo}`);
  const res = await o.io.fetchHtml(entry.url);
  if (!res.ok) throw new Error(`${entry.setNo}: HTTP ${res.status}`);
  if (!res.html.includes('IV_ITEM'))
    throw new Error(
      `${entry.setNo}: no inventory in response (blocked?). Save the page manually and use "setNo=file.html".`,
    );
  o.io.writeCache(name, res.html);
  await o.io.sleep(PAGE_DELAY_MS);
  return res.html;
}

async function loadChangelog(setNo: string, local: boolean, o: ScrapeOptions): Promise<ChangeGroup[]> {
  const name = `${setNo}.changelog.html`;
  const cached = o.refresh ? undefined : o.io.readCache(name);
  if (cached !== undefined) return parseChangelog(cached);
  if (local) return [];
  const res = await o.io.fetchHtml(CHANGELOG_URL(setNo));
  if (!res.ok) {
    o.warn(`  WARN ${setNo}: change log HTTP ${res.status}`);
    return [];
  }
  o.io.writeCache(name, res.html);
  await o.io.sleep(PAGE_DELAY_MS);
  return parseChangelog(res.html);
}

async function scrapeOne(entry: Entry & { type: 'local' | 'url' }, o: ScrapeOptions): Promise<SetInventory> {
  const local = entry.type === 'local';
  const html = local ? o.io.readFile(entry.path) : await loadInventoryHtml(entry, o);
  const src = local ? entry.path : entry.url;
  const inv = parseInventory(html, entry.setNo, src.startsWith('http') ? src : INVENTORY_URL(entry.setNo));
  inv.changes = await loadChangelog(entry.setNo, local, o);

  const { setNo } = entry;
  const { overrides, extra, merge } = o.data;
  const defs = defaultDefs(inv, overrides, extra, merge);
  if (!overrides[setNo]) {
    const merged = mergeChanges(effectiveChanges(inv), merge[setNo] ?? []);
    sameRunWarnings(setNo, merged).forEach(o.warn);
  }
  o.log(
    `${setNo}: ${inv.items.length} items, ${inv.changes.length} dated change groups, versions: ${defs.map((d) => d.name).join(' | ')}`,
  );
  const used = new Set(defs.flatMap((v) => v.alternates));
  const alts = new Set(inv.items.filter((i) => i.kind === 'alternate').map((i) => i.matchId));
  for (const m of alts) if (!used.has(m)) o.warn(`  WARN ${setNo}: match ID ${m} not in any version`);
  return inv;
}

/** Scrape every entry, in order, and return the inventories. */
export async function scrape(o: ScrapeOptions): Promise<SetInventory[]> {
  const sets: SetInventory[] = [];
  for (const entry of o.entries) {
    if (entry.type === 'listed') {
      sets.push({
        setNo: entry.setNo,
        name: entry.name,
        sourceUrl: CATALOG_URL(entry.setNo),
        items: [],
        changes: [],
        noInventory: true,
      });
      o.log(`${entry.setNo}: no inventory (listed only)`);
    } else sets.push(await scrapeOne(entry, o));
  }
  return sets;
}
